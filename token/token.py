# 零 Token 先行（Local-First）： 网络搜索、网页下载、HTML 清洗全部在本地纯 Python 执行，确认拿到有效数据前，绝不调用大模型。
# 内容硬截断（Context Truncation）： 一个普通网页往往有几万字，直接喂给 AI 会瞬间烧掉上万 Token！我们写工具时强制硬截断前 1200~1500 字符，只提取核心正文。
# 最大输出限制（max_tokens）： 强制设置大模型单次回复上限为 300~500 Token，杜绝模型“废话连篇”消耗额度。
# 防死循环熔断（recursion_limit）： 给 Agent 设死最大循环步数（比如最多允许搜索 1 次、读网页 1 次，上限 3 轮），防止它陷入死循环疯狂刷 API。


